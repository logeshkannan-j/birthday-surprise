"""Admin tool: rebuild the memories wall (screen 3) from the files in the memories/ folder.

How to use
  1. Put photos (.jpg .jpeg .png .webp .gif .heic*) and videos (.mp4 .webm .mov*) into  memories/
  2. Optional captions: add a line "filename = caption" to memories/captions.txt
  3. Run  update-memories.bat  (or:  python update_memories.py)

It writes web-sized copies to memories/web/ and the list the page reads, memories/list.js.
Delete a file from memories/ and run it again to remove it from the wall.
* .heic needs the pillow-heif package; .mov plays in Safari but often not in Chrome (convert to .mp4 if you can).
"""
import json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "memories")
WEB = os.path.join(SRC, "web")
IMG = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".heic", ".heif"}
VID = {".mp4", ".webm", ".mov", ".m4v"}
MAX_SIDE = 1400
VIDEO_WARN_MB = 25

try:
    from PIL import Image, ImageOps
    try:
        import pillow_heif  # optional
        pillow_heif.register_heif_opener()
    except Exception:
        pass
except Exception:
    Image = None


def slug(name):
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", os.path.splitext(name)[0]).strip("-") or "memory"
    return base[:60]


def captions():
    out = {}
    p = os.path.join(SRC, "captions.txt")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                out[k.strip().lower()] = v.strip()
    return out


def main():
    os.makedirs(WEB, exist_ok=True)
    caps = captions()
    files = sorted(f for f in os.listdir(SRC) if os.path.isfile(os.path.join(SRC, f)) and os.path.splitext(f)[1].lower() in IMG | VID)
    items, keep = [], set()
    for f in files:
        src = os.path.join(SRC, f)
        ext = os.path.splitext(f)[1].lower()
        cap = caps.get(f.lower(), "")
        if ext in IMG:
            if Image is None:
                if ext in {".heic", ".heif"}:
                    print("  skip (needs Pillow):", f); continue
                out = slug(f) + ext
                shutil.copy2(src, os.path.join(WEB, out)); w = h = 0
            else:
                try:
                    im = Image.open(src)
                    im = ImageOps.exif_transpose(im)
                except Exception as e:
                    print("  skip (cannot open):", f, e); continue
                if getattr(im, "is_animated", False) and ext == ".gif":
                    out = slug(f) + ".gif"; shutil.copy2(src, os.path.join(WEB, out)); w, h = im.size
                else:
                    im = im.convert("RGB")
                    im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
                    w, h = im.size
                    out = slug(f) + ".jpg"
                    im.save(os.path.join(WEB, out), "JPEG", quality=84, optimize=True, progressive=True)
            items.append({"src": "memories/web/" + out, "type": "image", "w": w, "h": h, "caption": cap})
        else:
            mb = os.path.getsize(src) / 1e6
            out = slug(f) + ext
            shutil.copy2(src, os.path.join(WEB, out))
            if mb > VIDEO_WARN_MB:
                print("  note: %s is %.0f MB - large videos load slowly on phones" % (f, mb))
            if ext == ".mov":
                print("  note: %s is .mov - may not play in Chrome/Android; .mp4 is safest" % f)
            items.append({"src": "memories/web/" + out, "type": "video", "w": 0, "h": 0, "caption": cap})  # the page reads the real size when it loads
        keep.add(out)
        print("  added", f)
    for f in os.listdir(WEB):
        if f not in keep:
            os.remove(os.path.join(WEB, f))
    with open(os.path.join(SRC, "list.js"), "w", encoding="utf-8") as fh:
        fh.write("// generated by update_memories.py - do not edit by hand\nwindow.MEMORIES=" + json.dumps(items, ensure_ascii=False, indent=1) + ";\n")
    print("memories wall: %d item(s) -> memories/list.js" % len(items))


if __name__ == "__main__":
    if not os.path.isdir(SRC):
        os.makedirs(SRC)
        print("created", SRC, "- put photos and videos there and run this again")
        sys.exit(0)
    main()
